"""Deterministic documentation generated from blueprints (single source of truth).

``doogle docs`` writes docs/DECISION_MATRIX.md and refreshes the README's
blueprint gallery between the ``doogle:gallery`` markers. Output depends only
on blueprint files (no timestamps, no ages), so ``doogle docs --check`` can
run in CI and fail when someone edits a blueprint without regenerating docs.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Iterable
from urllib.parse import quote

from .engine import Blueprint, Catalog

GALLERY_START = "<!-- doogle:gallery:start -->"
GALLERY_END = "<!-- doogle:gallery:end -->"
MATRIX_PATH = Path("docs") / "DECISION_MATRIX.md"
PLACEHOLDER_REPO = "https://github.com/OWNER/REPO"
REPO_URL_ENV = "DOOGLE_REPO_URL"
BADGE_COLOR = "2ea44f"  # neutral green; deliberately not a Google brand colour


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _sorted(bps: Iterable[Blueprint]) -> list[Blueprint]:
    return sorted(bps, key=lambda b: (b.category, b.id))


def _yes_no(flag: bool) -> str:
    return "yes" if flag else "no"


def render_decision_matrix(catalog: Catalog) -> str:
    bps = _sorted(catalog)
    lines = [
        "<!-- Generated by `doogle docs` from blueprints/*/blueprint.yaml. Do not edit by hand. -->",
        "",
        "# Decision matrix",
        "",
        "Pick the smallest stack that fits. Every row links to a guide; every blueprint lists the "
        "simpler or cheaper alternatives to consider first.",
        "",
        "| Blueprint | Category | Best for | Consider first instead | Google services | Public endpoint | "
        "High-risk steps | Manual steps | Tools | Verification |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for bp in bps:
        services = ", ".join(s["name"] for s in bp.services)
        high = sum(s.risk == "high" for s in bp.steps)
        manual = sum(s.manual for s in bp.steps)
        public = any(s.public_exposure for s in bp.steps)
        lines.append(
            f"| [`{bp.id}`](../blueprints/{bp.id}/GUIDE.md) | {_cell(bp.category)} | {_cell(bp.when_to_use[0])} | "
            f"{_cell(bp.when_not_to_use[0])} | {_cell(services)} | {_yes_no(public)} | {high} | {manual} | "
            f"{', '.join(t for t in bp.required_tools() if t not in ('test', 'curl')) or '-'} | "
            f"{bp.verification_status}, {bp.last_verified} |"
        )
    lines += ["", "Verification levels: `simulated` = run only against stub CLIs; `syntax-checked` = every "
              "subcommand and flag checked against the recorded CLI versions' `--help`; `live` = run end to end "
              "against a real throwaway project. See GOVERNANCE.md.", ""]
    for bp in bps:
        lines += [f"## {bp.name} (`{bp.id}`)", "", bp.tagline, "", "**Use it when**", ""]
        lines += [f"- {_cell(w)}" for w in bp.when_to_use]
        lines += ["", "**Do not use it when**", ""]
        lines += [f"- {_cell(w)}" for w in bp.when_not_to_use]
        lines += ["", f"**Cost:** {_cell(bp.estimated_cost)}", ""]
        versions = ", ".join(f"{k} {v}" for k, v in sorted(bp.verified_versions.items()))
        lines += [f"**Verified:** {bp.verification_status} on {bp.last_verified} ({versions}). "
                  f"Maintainer: {bp.maintainer}", ""]
        lines += [f"Try it: `doogle explain {bp.id}` then `doogle plan {bp.id}`", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_gallery(catalog: Catalog) -> str:
    lines = [GALLERY_START,
             "<!-- Generated by `doogle docs`. Edit the blueprints, not this table. -->",
             "",
             "| Blueprint | What you get | Consider first instead | Public? | Verification | Try it |",
             "|---|---|---|---|---|---|"]
    for bp in _sorted(catalog):
        public = "yes" if any(s.public_exposure for s in bp.steps) else "no"
        lines.append(f"| [**{_cell(bp.name)}**](blueprints/{bp.id}/GUIDE.md) | {_cell(bp.tagline)} | "
                     f"{_cell(bp.when_not_to_use[0])} | {public} | "
                     f"{bp.verification_status} ({bp.last_verified}) | `doogle plan {bp.id}` |")
    lines += ["", f"{len(catalog.blueprints)} blueprints. Full comparison: "
              "[docs/DECISION_MATRIX.md](docs/DECISION_MATRIX.md).", GALLERY_END]
    return "\n".join(lines)


def update_readme(text: str, gallery: str) -> str:
    start, end = text.find(GALLERY_START), text.find(GALLERY_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"README is missing the {GALLERY_START} / {GALLERY_END} markers")
    return text[:start] + gallery + text[end + len(GALLERY_END):]


def generate(catalog: Catalog, root: Path) -> dict[Path, str]:
    """Return {path: desired content} for every generated file."""
    root = Path(root)
    out = {root / MATRIX_PATH: render_decision_matrix(catalog)}
    readme = root / "README.md"
    if readme.is_file():
        out[readme] = update_readme(readme.read_text(encoding="utf-8"), render_gallery(catalog))
    return out


def stale_files(desired: dict[Path, str]) -> list[Path]:
    return [p for p, content in desired.items()
            if not p.is_file() or p.read_text(encoding="utf-8") != content]


def write(desired: dict[Path, str]) -> list[Path]:
    changed = stale_files(desired)
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(desired[path], encoding="utf-8")
    return changed


# --------------------------------------------------------------------------- share


def repo_url(explicit: str | None = None) -> str:
    return (explicit or os.environ.get(REPO_URL_ENV) or PLACEHOLDER_REPO).rstrip("/")


def _shields(text: str) -> str:
    return quote(text.replace("-", "--").replace("_", "__"), safe="")


def share_snippet(bp: Blueprint, url: str) -> dict:
    link = f"{url}/tree/main/blueprints/{bp.id}"
    badge = f"https://img.shields.io/badge/{_shields('built with')}-{_shields('doogle: ' + bp.id)}-{BADGE_COLOR}"
    badge_md = f"[![Built with a Doogle blueprint: {bp.id}]({badge})]({link})"
    services = ", ".join(s["name"] for s in bp.services)
    blurb = (f"This project was set up with the [{bp.id}]({link}) Doogle blueprint ({services}), "
             "planned as a dry run first and with a recorded teardown. Doogle is an independent "
             "community project, not affiliated with or endorsed by Google LLC.")
    return {"blueprint_id": bp.id, "link": link, "badge_url": badge, "badge_markdown": badge_md,
            "markdown": f"{badge_md}\n\n{blurb}\n", "placeholder_repo": url == PLACEHOLDER_REPO}
